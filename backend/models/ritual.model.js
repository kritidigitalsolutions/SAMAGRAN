import mongoose from "mongoose";

const ritualSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      default: "",
      trim: true,
    },
    status: {
      type: String,
      enum: ["active", "inactive"],
      default: "active",
    },
  },
  { timestamps: true }
);

ritualSchema.index({ title: 1 }, { unique: true });

export default mongoose.model("Ritual", ritualSchema);
